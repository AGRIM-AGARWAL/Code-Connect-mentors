// Builds supabase/03_seed.sql from data/mentors.json + data/interest_questions.json
// Usage: npm run seed   → then paste supabase/03_seed.sql into Supabase SQL Editor.
// Re-running is safe: it upserts mentors/questions and never touches student data
// or the mentor interest answers you set on the admin page.
import { readFileSync, writeFileSync } from 'node:fs'

const mentors = JSON.parse(readFileSync(new URL('../data/mentors.json', import.meta.url)))
const interest = JSON.parse(readFileSync(new URL('../data/interest_questions.json', import.meta.url)))

const s = (v) => (v == null ? 'null' : `'${String(v).replace(/'/g, "''")}'`)
const arr = (a) => `array[${a.map(s).join(', ')}]::text[]`

const errors = []
const ids = new Set()
for (const m of mentors) {
  if (!/^[a-z0-9_-]+$/.test(m.id)) errors.push(`mentor id "${m.id}" must be lowercase letters/numbers`)
  for (const q of m.skillQuestions) {
    if (ids.has(q.id)) errors.push(`duplicate question id ${q.id}`)
    ids.add(q.id)
    if (!(q.answer >= 0 && q.answer < q.options.length)) errors.push(`${q.id}: answer index out of range`)
  }
}
for (const k of interest.keys) {
  if (k.mentorOptions.length !== k.studentOptions.length) errors.push(`interest ${k.qkey}: option counts differ`)
}
if (errors.length) {
  console.error('Fix these first:\n - ' + errors.join('\n - '))
  process.exit(1)
}

const out = []
out.push('-- GENERATED by scripts/build-seed.mjs — edit data/*.json, then run `npm run seed`.')
out.push('begin;')

out.push('\n-- interest keys')
interest.keys.forEach((k, i) => {
  out.push(
    `insert into public.interest_keys (qkey, mentor_prompt, options, sort) values (${s(k.qkey)}, ${s(k.mentorPrompt)}, ${arr(k.mentorOptions)}, ${i})\n` +
      `  on conflict (qkey) do update set mentor_prompt = excluded.mentor_prompt, options = excluded.options, sort = excluded.sort;`,
  )
})

out.push('\n-- mentors')
mentors.forEach((m, i) => {
  out.push(
    `insert into public.mentors (id, name, tagline, highlights, github, linkedin, accent, photo_url, min_team, max_team, active, sort) values\n` +
      `  (${s(m.id)}, ${s(m.name)}, ${s(m.tagline)}, ${arr(m.highlights ?? [])}, ${s(m.github)}, ${s(m.linkedin)}, ${s(m.accent)}, ${s(m.photoUrl)}, ${m.minTeam ?? 5}, ${m.maxTeam ?? 8}, ${m.active ?? true}, ${i})\n` +
      `  on conflict (id) do update set name = excluded.name, tagline = excluded.tagline, highlights = excluded.highlights,\n` +
      `    github = excluded.github, linkedin = excluded.linkedin, accent = excluded.accent, photo_url = excluded.photo_url,\n` +
      `    active = excluded.active, sort = excluded.sort;  -- team sizes are NOT overwritten: they are edited on the admin page`,
  )
})

out.push('\n-- questions')
const keys = interest.keys
mentors.forEach((m, mi) => {
  m.skillQuestions.forEach((q, qi) => {
    out.push(
      `insert into public.questions (id, mentor_id, kind, qkey, prompt, options, correct, position) values\n` +
        `  (${s(q.id)}, ${s(m.id)}, 'skill', null, ${s(q.q)}, ${arr(q.options)}, ${q.answer}, ${qi})\n` +
        `  on conflict (id) do update set mentor_id = excluded.mentor_id, kind = excluded.kind, qkey = null, prompt = excluded.prompt,\n` +
        `    options = excluded.options, correct = excluded.correct, position = excluded.position, active = true;`,
    )
  })
  // interest: rotate so each mentor gets a different subset of keys
  const n = Math.min(interest.perMentor, keys.length)
  const picked = Array.from({ length: n }, (_, j) => keys[(mi + j) % keys.length])
  const pickedIds = []
  picked.forEach((k, j) => {
    const id = `${m.id}__${k.qkey}`
    pickedIds.push(id)
    out.push(
      `insert into public.questions (id, mentor_id, kind, qkey, prompt, options, correct, position) values\n` +
        `  (${s(id)}, ${s(m.id)}, 'interest', ${s(k.qkey)}, ${s(k.studentPrompt)}, ${arr(k.studentOptions)}, null, ${j})\n` +
        `  on conflict (id) do update set qkey = excluded.qkey, prompt = excluded.prompt, options = excluded.options,\n` +
        `    position = excluded.position, active = true;`,
    )
  })
  // retire questions removed from the JSON (kept for history, just inactive)
  const keep = [...m.skillQuestions.map((q) => q.id), ...pickedIds]
  out.push(`update public.questions set active = false where mentor_id = ${s(m.id)} and id not in (${keep.map(s).join(', ')});`)
})

out.push('\ncommit;')
writeFileSync(new URL('../supabase/03_seed.sql', import.meta.url), out.join('\n') + '\n')
console.log(`Wrote supabase/03_seed.sql — ${mentors.length} mentors, ${ids.size} skill questions, ${mentors.length * Math.min(interest.perMentor, keys.length)} interest questions.`)

// Also rebuild the one-paste setup file (01 + 02 + 03) so it never goes stale.
{
  const read = (f) => readFileSync(new URL(`../supabase/${f}`, import.meta.url), 'utf8')
  const all = [
    '-- Code Connect · Hypervision — FULL DATABASE SETUP (one paste)',
    '-- Generated from 01_registrations.sql + 02_quiz.sql + 03_seed.sql by `npm run seed`. Do not edit by hand.',
    '-- Safe to re-run: keeps student data and team sizes.',
    '-- After it runs, set the admin password with the last statement at the bottom (change the text!).',
    '',
    read('01_registrations.sql'),
    read('02_quiz.sql'),
    read('03_seed.sql'),
    '-- ── Set the admin password (uncomment, change, run once) ──',
    "-- update public.settings set admin_hash = extensions.crypt('CHANGE-ME', extensions.gen_salt('bf')) where id = 1;",
    '',
  ].join('\n')
  writeFileSync(new URL('../supabase/00_ALL_IN_ONE.sql', import.meta.url), all)
  console.log('Wrote supabase/00_ALL_IN_ONE.sql')
}
